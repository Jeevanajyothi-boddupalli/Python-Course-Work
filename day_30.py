    "# LIBRARY MANAGEMENT SYSTEM\n",
    "\n",
    "A Library Management System is a simple Python program used to\n",
    "manage books in a library.\n",
    "\n",
    "It can be used to store book details, display available books,\n",
    "borrow books, and return books.\n",
    "\n",
    "## DEEP COPY AND SHALLOW COPY\n",
    "\n",
    "Copying an object means creating another object with the same data.\n",
    "\n",
    "### SHALLOW COPY\n",
    "\n",
    "A shallow copy creates a new object, but nested objects inside it\n",
    "are still shared between the original and copied objects.\n",
    "\n",
    "It can be created using copy.copy().\n",
    "\n",
    "### DEEP COPY\n",
    "\n",
    "A deep copy creates a new object along with independent copies of\n",
    "all nested objects.\n",
    "\n",
    "It can be created using copy.deepcopy().\n",
    "\n",
    "## DIFFERENCE\n",
    "\n",
    "Shallow copy:\n",
    "- Creates a new outer object.\n",
    "- Nested objects are shared.\n",
    "- Changes to nested objects can affect both copies.\n",
    "\n",
    "Deep copy:\n",
    "- Creates a new outer object.\n",
    "- Nested objects are also copied.\n",
    "- Changes to nested objects do not affect the original object."
